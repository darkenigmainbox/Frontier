import assert from 'node:assert/strict';
import init from 'manifold-3d';
import {AutoDetailMask,DetailMask} from '../terrain/DetailMask.js';
import {ReadSpecification,ReadRecipe,EarliestStage} from '../terrain/CliffSpecification.js';
import {SolidPresets} from '../terrain/SolidFormation.js';
import {MouldSequence} from '../terrain/MouldSequence.js';
const s=ReadSpecification({...SolidPresets.Headland,Profile:'Headland',ErosionInward:0,ErosionOutward:0});
assert.equal(s.DetailMaskMode,'Auto');
const points=[];for(let x=-20;x<=20;x+=2)for(let y=0;y<=20;y+=2)points.push([x,y,-7]);
const weights=points.map(p=>AutoDetailMask(p,s));assert(weights.includes(0));assert(weights.includes(1));assert(weights.some(w=>w>0&&w<1));
for(const p of points){assert.equal(AutoDetailMask(p,s),AutoDetailMask(p,s));assert(AutoDetailMask(p,{...s,DetailAutoCoverage:.7})>=AutoDetailMask(p,{...s,DetailAutoCoverage:.3}));}
assert.notDeepEqual(weights,points.map(p=>AutoDetailMask(p,{...s,DetailAutoSeed:43})));
assert.notDeepEqual(weights,points.map(p=>AutoDetailMask(p,{...s,DetailAutoSize:10})));
const stamp={p:[0,10,0],n:[0,0,1],radius:4,strength:1,softness:1,target:0,stroke:1};
const full={...s,DetailAutoCoverage:1,DetailPaint:[stamp]};
assert.equal(DetailMask(stamp.p,stamp.n,full),1,'Auto ignores paint');
assert.equal(DetailMask(stamp.p,stamp.n,{...full,DetailMaskMode:'AutoPaint'}),0,'hybrid protects over Auto');
assert.equal(DetailMask(stamp.p,stamp.n,{...full,DetailMaskMode:'AutoPaint',DetailAutoCoverage:0,DetailPaint:[{...stamp,target:1}]}),1,'hybrid adds over Auto');
assert.equal(ReadRecipe({Format:'Frontier.PolygonCliff',Version:10,Specification:{}}).DetailMaskMode,'Paint');
assert.deepEqual(ReadRecipe({Format:'Frontier.PolygonCliff',Version:11,Specification:s}),s);
assert.throws(()=>ReadSpecification({...s,DetailMaskMode:'invalid'}));
for(const key of ['DetailAutoCoverage','DetailAutoSize','DetailAutoFalloff','DetailAutoSeed','DetailAutoHeightBias'])assert.equal(EarliestStage(s,{...s,[key]:s[key]+.1}),6);
const lib=await init();lib.setup();const seq=new MouldSequence(async()=>lib);
const result=await seq.Generate(s),d=result.Stages[5];
for(const key of ['OpenEdges','NonmanifoldEdges','NonmanifoldVertices','ZeroArea','WindingErrors','DuplicateTriangles'])assert.equal(d.Metrics[key],0);
assert(d.Detail.affectedVertices>0&&d.Detail.affectedVertices<d.Detail.mouldVerticesMoved);
assert(d.Detail.removedVolume>0);console.log('Auto default',d.Detail);
const none=await seq.Generate({...s,DetailAutoCoverage:0});assert.deepEqual(none.Stages[5].Meshes,none.Stages[4].Meshes);assert.deepEqual(none.ExecutedStages,[6]);
const changed=await seq.Generate({...s,DetailAutoSeed:43});assert.deepEqual(changed.ExecutedStages,[6]);assert.notEqual(changed.Stages[5].Detail.finalVolume,d.Detail.finalVolume);
console.log('PASS: Auto default, mixed/soft coverage, seed/size variation, monotonic coverage, hybrid add/protect, migration, CSG topology and detail-only cache.');
