import assert from 'node:assert/strict';
import fs from 'node:fs';
import {RepairExchange} from '../terrain/ExchangeRepair.js';
import {MeshMetrics} from '../terrain/PolyhedronSolver.js';
const mesh=JSON.parse(fs.readFileSync(new URL('./fixtures/exchange-ground-corner.json',import.meta.url)));
const before=structuredClone(mesh),metrics=MeshMetrics(mesh);
assert.equal(metrics.ZeroArea,1,'captured production-path failure');
assert.equal(metrics.OpenEdges,0);
assert.equal(RepairExchange(mesh),1);
const after=MeshMetrics(mesh);
for(const key of ['ZeroArea','OpenEdges','NonmanifoldEdges','NonmanifoldVertices','DuplicateTriangles','WindingErrors'])assert.equal(after[key],0,key);
assert.equal(after.Vertices,metrics.Vertices-1);assert.equal(after.Triangles,metrics.Triangles-2);
assert(Math.abs(after.Volume-metrics.Volume)<1e-5);
const originalPoints=new Set(before.Vertices.map(p=>p.join(','))),added=mesh.Vertices.filter(p=>!originalPoints.has(p.join(',')));
assert.equal(added.length,1,'midpoint, not endpoint-only repair');
assert(added[0].every(v=>Math.fround(v)===v),'repair survives Float32 export');
assert(before.Vertices.filter(p=>Math.hypot(...p.map((v,k)=>v-added[0][k]))<=1e-5).length>=2,'movement bounded to microscopic edge');
// Idempotence: once valid, subsequent export cleanup leaves the mesh unchanged.
const once=JSON.stringify(mesh);assert.equal(RepairExchange(mesh),0);assert.equal(JSON.stringify(mesh),once);
console.log(JSON.stringify({passed:true,beforeZeroArea:metrics.ZeroArea,afterZeroArea:after.ZeroArea,vertices:after.Vertices,triangles:after.Triangles,volumeChange:after.Volume-metrics.Volume,newFloat32Point:added[0]},null,2));
const deep=JSON.parse(fs.readFileSync(new URL('./fixtures/exchange-deep-corner.json',import.meta.url))),deepBefore=MeshMetrics(deep);
assert.equal(deepBefore.ZeroArea,1);
RepairExchange(deep);
assert.equal(MeshMetrics(deep).ZeroArea,1,'strict 8-degree cleanup cannot repair the deeper corner');
assert.equal(RepairExchange(deep,1e-5,.95),1);
const deepAfter=MeshMetrics(deep);
for(const key of ['ZeroArea','OpenEdges','NonmanifoldEdges','NonmanifoldVertices','DuplicateTriangles','WindingErrors'])assert.equal(deepAfter[key],0,key);
assert(Math.abs(deepAfter.Volume-deepBefore.Volume)<1e-5);
console.log('PASS: deeper corner repaired with bounded, intersection-checked fallback; validator unchanged.');
